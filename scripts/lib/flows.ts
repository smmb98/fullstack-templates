/** Shared flow-card and feature-registry logic. The CLI wrappers stay thin. */

export interface FeatureNavLike {
  label: string;
  href: string;
  placement: "header" | "footer";
}

export interface FeatureMetaLike {
  id: string;
  title: string;
  flag: string;
  routes: string[];
  endpoints: string[];
  states: string[];
  scenarios: Record<string, string>;
  dependsOn: string[];
  tag: string;
  nav?: FeatureNavLike;
}

export interface VirtualFs {
  /** Repo-relative path, POSIX separators. */
  exists(path: string): boolean;
  readFile(path: string): string;
  /** Every file under dir (recursive), repo-relative paths. Missing dirs return []. */
  walk(dir: string): string[];
}

export const INDEX_HEADER = "GENERATED by pnpm flows:gen. Do not edit.";

export function indexLine(meta: FeatureMetaLike): string {
  const list = (values: readonly string[]) => (values.length ? values.join(", ") : "-");
  const scenarios = Object.entries(meta.scenarios)
    .map(([scenario, state]) => `${scenario}->${state}`)
    .join(", ");
  return [
    meta.id,
    list(meta.routes),
    meta.flag,
    list(meta.states),
    scenarios || "-",
    list(meta.dependsOn),
    `docs/flows/${meta.id}.md`,
  ].join(" | ");
}

export function renderIndex(metas: readonly FeatureMetaLike[]): string {
  const lines = [...metas]
    .sort((a, b) => a.id.localeCompare(b.id))
    .map(indexLine);
  return [INDEX_HEADER, ...lines].join("\n") + "\n";
}

export function findDependencyCycles(metas: readonly FeatureMetaLike[]): string[][] {
  const byId = new Map(metas.map((meta) => [meta.id, meta]));
  const cycles: string[][] = [];
  const state = new Map<string, "visiting" | "done">();
  const stack: string[] = [];

  const visit = (id: string) => {
    const current = state.get(id);
    if (current === "done") return;
    if (current === "visiting") {
      const start = stack.indexOf(id);
      cycles.push([...stack.slice(start), id]);
      return;
    }
    state.set(id, "visiting");
    stack.push(id);
    for (const dependency of byId.get(id)?.dependsOn ?? []) {
      if (byId.has(dependency)) visit(dependency);
    }
    stack.pop();
    state.set(id, "done");
  };

  for (const meta of metas) visit(meta.id);
  return cycles;
}

export function unknownDependencies(metas: readonly FeatureMetaLike[]): string[] {
  const ids = new Set(metas.map((meta) => meta.id));
  return metas.flatMap((meta) =>
    meta.dependsOn.filter((dep) => !ids.has(dep)).map((dep) => `${meta.id} -> ${dep}`),
  );
}

const IMPORT_PATTERN = /from\s+["']([^"']+)["']/g;

/** Returns violations of "features import other features only via index.ts and dependsOn". */
export function featureImportViolations(
  metas: readonly FeatureMetaLike[],
  fs: VirtualFs,
  featuresDir: string,
): string[] {
  const byId = new Map(metas.map((meta) => [meta.id, meta]));
  const violations: string[] = [];

  for (const meta of metas) {
    for (const file of fs.walk(`${featuresDir}/${meta.id}`)) {
      if (!/\.(ts|tsx)$/.test(file) || file.endsWith(".test.ts") || file.endsWith(".test.tsx")) {
        continue;
      }
      const source = fs.readFile(file);
      for (const match of source.matchAll(IMPORT_PATTERN)) {
        const specifier = match[1];
        const index = specifier.indexOf("features/");
        if (index === -1) continue;
        const tail = specifier.slice(index + "features/".length);
        const [target, ...rest] = tail.split("/");
        if (!target || target === meta.id || !byId.has(target)) continue;
        if (!meta.dependsOn.includes(target)) {
          violations.push(`${file} imports ${target} but does not declare it in dependsOn`);
        }
        if (rest.length > 0) {
          violations.push(`${file} imports internals of ${target}; import ${target}/index instead`);
        }
      }
    }
  }
  return violations;
}

/** Shared code must never import a feature. */
export function sharedImportViolations(metas: readonly FeatureMetaLike[], fs: VirtualFs): string[] {
  const ids = new Set(metas.map((meta) => meta.id));
  const violations: string[] = [];
  const sharedRoots = ["packages", "apps/shop/src/lib", "apps/shop/src/config"];
  for (const root of sharedRoots) {
    for (const file of fs.walk(root)) {
      if (!/\.(ts|tsx)$/.test(file) || file.endsWith(".test.ts") || file.endsWith(".test.tsx")) {
        continue;
      }
      if (file.includes("/features/")) continue;
      const source = fs.readFile(file);
      for (const match of source.matchAll(IMPORT_PATTERN)) {
        const specifier = match[1];
        const index = specifier.indexOf("features/");
        if (index === -1) continue;
        const target = specifier.slice(index + "features/".length).split("/")[0];
        if (target && ids.has(target)) {
          violations.push(`${file} imports feature ${target}; shared code must not depend on features`);
        }
      }
    }
  }
  return violations;
}

export function routeFile(appDir: string, route: string): string {
  if (route === "/") return `${appDir}/page.tsx`;
  return `${appDir}${route.replace(/\/$/, "")}/page.tsx`;
}

export interface CheckInput {
  metas: readonly FeatureMetaLike[];
  flags: Record<string, unknown>;
  fs: VirtualFs;
  appDir: string;
  featuresDir: string;
  docsFlowsDir: string;
  e2eDir: string;
  index: string;
}

export function checkFeatures(input: CheckInput): string[] {
  const { metas, flags, fs, appDir, featuresDir, docsFlowsDir, e2eDir, index } = input;
  const problems: string[] = [];

  for (const meta of metas) {
    const featureDir = `${featuresDir}/${meta.id}`;
    const card = `${docsFlowsDir}/${meta.id}.md`;
    if (!fs.exists(card)) problems.push(`${meta.id}: missing flow card ${card}`);
    else if (fs.readFile(card).split("\n").length > 60) {
      problems.push(`${card}: card exceeds 60 lines`);
    }

    for (const route of meta.routes) {
      const file = routeFile(appDir, route);
      if (!fs.exists(file)) problems.push(`${meta.id}: route ${route} has no ${file}`);
    }

    const stories = fs.walk(featureDir).filter((file) => file.endsWith(".stories.tsx"));
    const storySource = stories.map((file) => fs.readFile(file)).join("\n");
    for (const state of meta.states) {
      if (!storySource.includes(`name: "${state}"`)) {
        problems.push(`${meta.id}: state "${state}" has no story named "${state}"`);
      }
    }

    const spec = `${e2eDir}/${meta.id}.spec.ts`;
    if (!fs.exists(spec)) problems.push(`${meta.id}: missing e2e spec ${spec}`);
    else if (!fs.readFile(spec).includes(`@${meta.tag}`)) {
      problems.push(`${spec}: missing tag @${meta.tag}`);
    }

    if (!(meta.flag in flags)) problems.push(`${meta.id}: flag "${meta.flag}" missing from features.config.json`);

    for (const scenario of Object.keys(meta.scenarios)) {
      if (!(scenario in (meta.scenarios as Record<string, string>))) {
        problems.push(`${meta.id}: scenario ${scenario} has no expected state`);
      }
    }
  }

  const featureIds = new Set(metas.map((meta) => meta.id));
  for (const flag of Object.keys(flags)) {
    if (!metas.some((meta) => meta.flag === flag)) {
      problems.push(`features.config.json: orphaned flag "${flag}"`);
    }
  }
  for (const cardFile of fs.walk(docsFlowsDir)) {
    if (!cardFile.endsWith(".md")) continue;
    const name = cardFile.split("/").pop() ?? "";
    if (name === "INDEX.md" || name.startsWith("_")) continue;
    const id = name.replace(/\.md$/, "");
    if (!featureIds.has(id)) problems.push(`${cardFile}: card has no feature.meta.ts`);
  }

  problems.push(...findDependencyCycles(metas).map((cycle) => `dependency cycle: ${cycle.join(" -> ")}`));
  problems.push(...unknownDependencies(metas).map((pair) => `unknown dependency: ${pair}`));
  problems.push(...featureImportViolations(metas, fs, featuresDir));
  problems.push(...sharedImportViolations(metas, fs));

  if (fs.exists(`${docsFlowsDir}/INDEX.md`)) {
    const current = fs.readFile(`${docsFlowsDir}/INDEX.md`);
    if (current.replace(/\r\n/g, "\n") !== index) {
      problems.push("docs/flows/INDEX.md is out of date; run pnpm flows:gen");
    }
  } else {
    problems.push("docs/flows/INDEX.md is missing; run pnpm flows:gen");
  }

  return problems;
}
