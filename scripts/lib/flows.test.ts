import { describe, expect, it } from "vitest";
import {
  checkFeatures,
  findDependencyCycles,
  renderIndex,
  type FeatureMetaLike,
  type VirtualFs,
} from "./flows";

function memoryFs(files: Record<string, string>): VirtualFs {
  return {
    exists: (path) => path in files,
    readFile: (path) => {
      if (!(path in files)) throw new Error(`no file ${path}`);
      return files[path];
    },
    walk: (dir) => Object.keys(files).filter((file) => file.startsWith(`${dir}/`)).sort(),
  };
}

const meta: FeatureMetaLike = {
  id: "catalog-listing",
  title: "Catalog listing",
  flag: "catalogListing",
  routes: ["/products"],
  endpoints: ["products.list"],
  states: ["ready", "loading"],
  scenarios: { "error-500": "error:http" },
  dependsOn: [],
  tag: "catalog-listing",
};

const index = renderIndex([meta]);

describe("flows", () => {
  it("renders one pipe-separated line per feature plus the generated header", () => {
    expect(index.split("\n")[0]).toContain("GENERATED by pnpm flows:gen");
    expect(index).toContain(
      "catalog-listing | /products | catalogListing | ready, loading | error-500->error:http | - | docs/flows/catalog-listing.md",
    );
  });

  it("finds dependency cycles", () => {
    const cycles = findDependencyCycles([
      { ...meta, id: "a", dependsOn: ["b"] },
      { ...meta, id: "b", dependsOn: ["a"] },
    ]);
    expect(cycles[0]).toEqual(["a", "b", "a"]);
  });

  it("reports missing card, story, spec, route, flag and drift", () => {
    const problems = checkFeatures({
      metas: [meta],
      flags: {},
      fs: memoryFs({}),
      appDir: "apps/shop/src/app",
      featuresDir: "apps/shop/src/features",
      docsFlowsDir: "docs/flows",
      e2eDir: "apps/shop/e2e",
      index,
    });
    expect(problems).toEqual(
      expect.arrayContaining([
        expect.stringContaining("missing flow card"),
        expect.stringContaining("route /products has no"),
        expect.stringContaining('state "ready" has no story'),
        expect.stringContaining("missing e2e spec"),
        expect.stringContaining('flag "catalogListing" missing'),
        expect.stringContaining("INDEX.md is missing"),
      ]),
    );
  });

  it("passes a complete feature", () => {
    const problems = checkFeatures({
      metas: [meta],
      flags: { catalogListing: true },
      fs: memoryFs({
        "apps/shop/src/app/products/page.tsx": "export default function Page() {}",
        "apps/shop/src/features/catalog-listing/feature.meta.ts": "",
        "apps/shop/src/features/catalog-listing/listing.stories.tsx":
          'export const Ready = { name: "ready" };\nexport const Loading = { name: "loading" };',
        "apps/shop/e2e/catalog-listing.spec.ts": 'test("works @catalog-listing", () => {});',
        "docs/flows/catalog-listing.md": "# card",
        "docs/flows/INDEX.md": index,
      }),
      appDir: "apps/shop/src/app",
      featuresDir: "apps/shop/src/features",
      docsFlowsDir: "docs/flows",
      e2eDir: "apps/shop/e2e",
      index,
    });
    expect(problems).toEqual([]);
  });

  it("flags imports of feature internals and undeclared dependencies", () => {
    const other: FeatureMetaLike = {
      ...meta,
      id: "other",
      flag: "otherFlag",
      routes: [],
      states: [],
      scenarios: {},
      tag: "other",
    };
    const problems = checkFeatures({
      metas: [meta, other],
      flags: { catalogListing: true, otherFlag: true },
      fs: memoryFs({
        "apps/shop/src/features/catalog-listing/feature.meta.ts": "",
        "apps/shop/src/features/catalog-listing/use-other.ts":
          'import { x } from "@/features/other/components/x";',
      }),
      appDir: "apps/shop/src/app",
      featuresDir: "apps/shop/src/features",
      docsFlowsDir: "docs/flows",
      e2eDir: "apps/shop/e2e",
      index,
    });
    expect(problems.some((problem) => problem.includes("does not declare it in dependsOn"))).toBe(
      true,
    );
  });
});
